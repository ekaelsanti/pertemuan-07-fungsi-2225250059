# Latihan 2: Luas Persegi Panjang dengan Return Value
def luas_persegi_panjang(p, l):
    return p * l

# Pengujian dengan beberapa test case
print("Luas (8, 5)   =", luas_persegi_panjang(8, 5))
print("Luas (2.5, 4) =", luas_persegi_panjang(2.5, 4))
print("Luas (0, 7)   =", luas_persegi_panjang(0, 7))